using System.Collections.Generic;
using System.IO;
using Odyssey.Director.Sim;
using UnityEngine;

namespace Odyssey.Director.ML
{
    /// <summary>
    /// Play-mode evaluation: runs Fixed, Heuristic and RL directors against the same scripted bot
    /// players and seeds, then writes results/director_eval.md and results/director_eval.csv.
    /// </summary>
    public class DirectorEvaluator : MonoBehaviour
    {
        [SerializeField] private DirectorAgent agent = null;
        [SerializeField] private int runsPerSkill = 300;
        [SerializeField] private int baseSeed = 1000;
        [SerializeField] private bool quitWhenDone = true;

        private string _status = "Evaluating...";

        private void Start()
        {
            var results = new List<EvalResult>();
            var rl = agent != null ? new RLDirector(agent) : null;
            var directors = new List<IDirector> { new FixedDirector(), new HeuristicDirector() };
            if (rl != null) directors.Add(rl);

            foreach (var d in directors)
                foreach (var skill in SkillProfile.All)
                    results.Add(DirectorEvaluation.Run(d, skill, runsPerSkill, baseSeed));

            string dir = Path.GetFullPath(Path.Combine(Application.dataPath, "..", "results"));
            Directory.CreateDirectory(dir);
            string table = DirectorEvaluation.ToMarkdownTable(results);
            string md =
                "# AI Director evaluation\n\n" +
                $"Generated by `DirectorEvaluator` (scene `DirectorEval`) on {System.DateTime.Now:yyyy-MM-dd HH:mm}.\n\n" +
                $"- Runs per (director, skill): {runsPerSkill}, seeds {baseSeed}..{baseSeed + runsPerSkill - 1} (identical for every director)\n" +
                $"- Segments per run: {RunSimulator.SegmentsPerRun}; a run fails at {RunSimulator.MaxDeaths} deaths\n" +
                $"- In band: HP lost per segment in [{ChallengeBand.HpLostMin:P0}, {ChallengeBand.HpLostMax:P0}] with no death\n" +
                $"- RL model assigned: {(rl != null && rl.HasModel ? "yes" : "NO (RL row = heuristic fallback, not a trained policy)")}\n" +
                "- Players are the scripted simulated players (Novice/Average/Expert), not humans.\n\n" +
                table;
            File.WriteAllText(Path.Combine(dir, "director_eval.md"), md);
            File.WriteAllText(Path.Combine(dir, "director_eval.csv"), DirectorEvaluation.ToCsv(results));
            Debug.Log(md);
            _status = "Done. Wrote " + Path.Combine(dir, "director_eval.md");

#if UNITY_EDITOR
            if (quitWhenDone) UnityEditor.EditorApplication.isPlaying = false;
#else
            if (quitWhenDone) Application.Quit();
#endif
        }

        private void OnGUI() => GUI.Label(new Rect(10, 10, 900, 40), _status);
    }
}
