JUMP_UP, REACH = 2, 4


def norm(name):
    rows = maps[name].strip("\n").split("\n")
    w = max(len(r) for r in rows)
    return [r.ljust(w, ".")[:w] for r in rows]


def analyse(name):
    rows = norm(name)
    H, W = len(rows), len(rows[0])
    cell = lambda x, y: rows[H - 1 - y][x] if 0 <= x < W and 0 <= y < H else "."
    solid = lambda x, y: cell(x, y) == "#"
    support = lambda x, y: cell(x, y) == "#"
    stand = {(x, y) for x in range(W) for y in range(1, H)
             if not solid(x, y) and not solid(x, y + 1) and support(x, y - 1)}
    def clear_path(x, y, x2, y2):
        # the player (2 cells tall) must fit through every column between the two spots at the higher level
        top = max(y, y2)
        lo, hi = min(x, x2), max(x, x2)
        return all(not solid(xi, top) and not solid(xi, top + 1) for xi in range(lo, hi + 1))

    start = [(x, y) for (x, y) in stand if x <= 1]
    seen, todo = set(start), list(start)
    while todo:
        x, y = todo.pop()
        for (x2, y2) in stand:
            if (x2, y2) in seen:
                continue
            dx, dy = abs(x2 - x), y2 - y
            if not clear_path(x, y, x2, y2):
                continue
            if (dx <= 1 and dy == 0) or (-12 <= dy <= JUMP_UP and dx <= REACH + max(0, -dy) // 2):
                seen.add((x2, y2))
                todo.append((x2, y2))
    crossable = any(x >= W - 2 for (x, _) in seen)
    enemies = [(x, H - 1 - r) for r, row in enumerate(rows) for x, c in enumerate(row) if c in "mr"]
    floating = [(x, y) for (x, y) in enemies if not support(x, y - 1)]
    stray = sorted({c for row in rows for c in row} - set(".#^mrPX"))
    ok = bool(start) and crossable and not floating and not stray and H == 12
    print(f"{'OK  ' if ok else 'FAIL'} {name:12s} {W}x{H} crossable={crossable} enemies={len(enemies)} floating={floating} unknown_chars={stray}")
    return ok


def write_cs(path):
    out = ["// <auto-generated> by tools/chunk_maps.py --write. Edit the maps there, not here. </auto-generated>",
           "using System.Collections.Generic;", "using Odyssey.LevelGen;", "using UnityEngine;", "",
           "namespace Odyssey.EditorTools", "{",
           "    /// <summary>Default chunk maps (validated for reachability by tools/chunk_maps.py).</summary>",
           "    public static class DefaultChunks", "    {", "        public struct Entry", "        {",
           "            public string Id; public ChunkKind Kind; public int Difficulty; public Color Tint; public string Map;",
           "        }", "", "        public static readonly List<Entry> All = new List<Entry>", "        {"]
    for cid, (kind, diff, tint) in META.items():
        body = "\n".join(norm(cid))
        out.append(f'            new Entry {{ Id = "{cid}", Kind = ChunkKind.{kind}, Difficulty = {diff}, '
                   f'Tint = new Color({tint}), Map = @"\n{body}" }},')
    out += ["        };", "    }", "}", ""]
    with open(path, "w", newline="\n") as fh:
        fh.write("\n".join(out))
    print("wrote", path)


